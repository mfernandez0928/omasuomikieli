type Extra = Pick<ReplyPair, 'note' | 'noteTl' | 'puhekieli'>;

function pair(
  num: number,
  category: ReplyCategoryId,
  level: Level,
  fi: [string, string],
  en: [string, string],
  tl: [string, string],
  extra: Extra = {},
): ReplyPair {
  return {
    id: `rp-${String(num).padStart(2, '0')}`,
    num,
    category,
    level,
    fi: { q: fi[0], a: fi[1] },
    en: { q: en[0], a: en[1] },
    tl: { q: tl[0], a: tl[1] },
    ...extra,
    source: null,
    verification: 'linguistically-checked',
  };
}

