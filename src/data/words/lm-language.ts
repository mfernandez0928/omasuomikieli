import type { SourceRef, Word } from '@/types';

/**
 * Words about language and about describing things.
 *
 *  - conjunctions from the KONJUNKTIOITA sheet (PDF 36, Oikeesti aikuisten 2
 *    printed page 40), which glosses each one in English;
 *  - postpositions from the Kappale 6 spread (PDF 16-17, printed pages
 *    194-195), all of which govern the genitive;
 *  - the names of punctuation marks and of text formatting (PDF 23-24);
 *  - the adjective opposites from Kappale 4 (PDF 26, printed page 35);
 *  - the personal-detail nouns the conversation cards ask about (PDF 27-28).
 *
 * The packet's email address and personal identity code are textbook filler
 * and are not reproduced anywhere in this file.
 */

function conj(term: string, gloss: string): SourceRef {
  return {
    bookId: 'lm',
    book: 'Learning Materials (scanned course packet)',
    chapter: 'Ammatit ja konjunktiot',
    pdfPage: 36,
    sourceTerm: term,
    note: `printed page 40 (Oikeesti aikuisten 2); the sheet glosses it "${gloss}"`,
  };
}

function postp(term: string): SourceRef {
  return {
    bookId: 'lm',
    book: 'Learning Materials (scanned course packet)',
    chapter: 'Kappale 6: Postpositiot',
    pdfPage: 16,
    sourceTerm: term,
    note: 'printed page 194',
  };
}

function mark(pdfPage: number, term: string): SourceRef {
  return {
    bookId: 'lm',
    book: 'Learning Materials (scanned course packet)',
    chapter: 'Lyhenteitä ja välimerkkejä',
    pdfPage,
    sourceTerm: term,
  };
}

