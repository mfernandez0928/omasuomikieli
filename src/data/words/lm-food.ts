/**
 * Food words from the Kappale 9 picture page (PDF 25, printed page 75) and the
 * shop compounds from the yhdyssana exercise (PDF 30, printed page 34).
 *
 * Only the entries the dictionary did not already hold are here: tomaatti,
 * kurkku, porkkana, kaali, salaatti, peruna, sipuli, valkosipuli, herne,
 * omena, appelsiini, mansikka, broileri and jauheliha were already in it.
 *
 * Four berries have no established Tagalog name, so the gloss describes them
 * instead of inventing one. Guessing a name here would be worse than saying
 * plainly what the berry is.
 */

function veg(pdfPage: number, printed: number, term: string): SourceRef {
  return {
    bookId: 'lm',
    book: 'Learning Materials (scanned course packet)',
    chapter: 'Kappale 9: ruokasanasto',
    pdfPage,
    section: 'SANASTO',
    sourceTerm: term,
    note: `printed page ${printed}`,
  };
}

