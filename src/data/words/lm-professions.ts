import type { SourceRef, Word } from '@/types';

/**
 * Professions from the Kappale 9 picture spread (PDF 37-38), and the nine
 * profession verbs from the matching exercise in Oikeesti aikuisten 1
 * (PDF 35, printed page 100).
 *
 * The matching exercise is the reason the verbs are here: almost every Finnish
 * profession name is the verb plus -ja/-jä, so learning the pair together
 * gives you both words for the price of one. Each entry below cross-links to
 * its partner.
 *
 * Already in the dictionary and so not repeated: lääkäri, sairaanhoitaja,
 * myyjä, kokki, laulaja, kampaaja, toimittaja, yrittäjä, insinööri, hoitaja,
 * and the verbs hoitaa, kalastaa, keittää, kirjoittaa, myydä, ommella,
 * opettaa, rakentaa, siivota.
 */

function amm(pdfPage: number, term: string): SourceRef {
  return {
    bookId: 'lm',
    book: 'Learning Materials (scanned course packet)',
    chapter: 'Kappale 9: Sanasto - ammatit',
    pdfPage,
    section: 'SANASTO',
    sourceTerm: term,
  };
}

function verb(term: string): SourceRef {
  return {
    bookId: 'lm',
    book: 'Learning Materials (scanned course packet)',
    chapter: 'Ammatit ja konjunktiot',
    pdfPage: 35,
    sourceTerm: term,
    note: 'printed page 100 (Oikeesti aikuisten 1), tehtävä: yhdistä ammatti ja verbi',
  };
}

