import type { SourceRef, Word } from '@/types';

/**
 * Nature vocabulary from the scanned packet: the Kappale 3 SANASTO spreads
 * (PDF 31, 39, 40, 41) and the wild-animal page that opens them.
 *
 * These pages are picture dictionaries: a drawing with the word under it and
 * nothing else. So each entry here carries the headword the page prints, and
 * the principal parts are worked out from standard morphology rather than read
 * off the page - which is what `linguistically-checked` means. Where a word's
 * inflection is irregular enough to be worth saying out loud (susi, mato,
 * virtahepo, kuusi) the note says so.
 *
 * Nothing is included that could not be made out on the scan.
 */

function src(pdfPage: number, printed: number | undefined, term: string): SourceRef {
  return {
    bookId: 'lm',
    book: 'Learning Materials (scanned course packet)',
    chapter: 'Kappale 3: Sanasto - luonto',
    pdfPage,
    section: 'SANASTO',
    sourceTerm: term,
    note: printed ? `printed page ${printed}` : undefined,
  };
}

