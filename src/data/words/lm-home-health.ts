import type { SourceRef, Word } from '@/types';

/**
 * Home and health words from the packet.
 *
 * Three sources feed this file:
 *  - the kodintavara riddle sheet (PDF 18), whose twenty answers were all
 *    correct on the scan and are reused here as the glosses;
 *  - Kappale 7 "Minulla on stressiä" and its dialogues (PDF 1, 14, 15);
 *  - the postposition spread (PDF 16-17), which supplies the classroom objects
 *    the examples are built from.
 *
 * The listening exercise on PDF 1 is not used: its recording is not in the
 * packet, so its answers could not be checked.
 */

function home(term: string): SourceRef {
  return {
    bookId: 'lm',
    book: 'Learning Materials (scanned course packet)',
    chapter: 'Kodintavarat ja huonekalut',
    pdfPage: 18,
    sourceTerm: term,
    note: 'tehtävä: Mikä kodintavara tai huonekalu?',
  };
}

function health(pdfPage: number, printed: number | undefined, term: string): SourceRef {
  return {
    bookId: 'lm',
    book: 'Learning Materials (scanned course packet)',
    chapter: 'Kappale 7: Minulla on stressiä',
    pdfPage,
    sourceTerm: term,
    note: printed ? `printed page ${printed}` : undefined,
  };
}

function classroom(term: string): SourceRef {
  return {
    bookId: 'lm',
    book: 'Learning Materials (scanned course packet)',
    chapter: 'Kappale 6: Postpositiot',
    pdfPage: 16,
    sourceTerm: term,
    note: 'printed page 194',
  };
}

